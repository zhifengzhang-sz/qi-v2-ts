/// <reference types="node" />
// Writes src/pipe.ts: pipe and flow, one signature per length up to pipe.toml's max (a chain's types are checked
// link by link only through such signatures; a recursive type would lose the inference inside each step), and
// test/pipe.limit.test.ts, which types a chain of max steps and expects max + 1 refused, so that the setting is
// checked where it acts, in the types. Run by make ts before the checks; both files are then formatted by Biome,
// so the check sees what is committed.

import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import config from "../pipe.toml";

const max = Number(config.max);
if (!Number.isInteger(max) || max < 1) {
  console.error(`pipe.toml: max must be a positive integer, got ${String(config.max)}`);
  process.exit(1);
}

const lengths = Array.from({ length: max }, (_, i) => i + 1);
const types = (n: number) => Array.from({ length: n + 1 }, (_, i) => `A${i}`);
const steps = (n: number) => Array.from({ length: n }, (_, i) => `f${i + 1}: F<A${i}, A${i + 1}>`);

const pipeSignature = (n: number) =>
  `export function pipe<${types(n).join(", ")}>(a: A0, ${steps(n).join(", ")}): A${n};`;
const flowSignature = (n: number) =>
  `export function flow<${types(n).join(", ")}>(${steps(n).join(", ")}): F<A0, A${n}>;`;

const header = `// GENERATED by scripts/gen-pipe.ts from pipe.toml (max = ${max}); edit those, not this file.`;

const source = `${header}
// pipe and flow: composition left to right, so that curried, data-last functions read in order.

type F<A, B> = (a: A) => B;

export const maxSteps = ${max};

export function pipe<A0>(a: A0): A0;
${lengths.map(pipeSignature).join("\n")}
export function pipe(a: unknown, ...fs: readonly F<unknown, unknown>[]): unknown {
  return fs.reduce((x, f) => f(x), a);
}

${lengths.map(flowSignature).join("\n")}
export function flow(...fs: readonly F<unknown, unknown>[]): F<unknown, unknown> {
  return (a) => fs.reduce((x, f) => f(x), a);
}

export const identity = <A>(a: A): A => a;
`;

const incs = (n: number) => Array.from({ length: n }, () => "inc").join(", ");

const limitTest = `${header}
// pipe and flow at the limit: a typed chain of max steps compiles and runs; one step more is refused by tsc.

import { describe, expect, it } from "vitest";
import { flow, maxSteps, pipe } from "../src/index.ts";

const inc = (n: number): number => n + 1;

describe("pipe and flow at pipe.toml's max (${max})", () => {
  it("type and run a chain of max steps", () => {
    expect(pipe(0, ${incs(max)})).toBe(maxSteps);
    expect(flow(${incs(max)})(0)).toBe(maxSteps);
  });
  // The steps in one constant, so that each call stays on one line under its @ts-expect-error.
  it("refuse one step more, in the types", () => {
    const over = [${incs(max + 1)}] as const;
    // @ts-expect-error: max + 1 steps
    expect(pipe(0, ...over)).toBe(maxSteps + 1);
    // @ts-expect-error: max + 1 steps
    expect(flow(...over)(0)).toBe(maxSteps + 1);
  });
});
`;

const write = (relative: string, text: string): string => {
  const path = fileURLToPath(new URL(relative, import.meta.url));
  writeFileSync(path, text);
  return path;
};

const paths = [write("../src/pipe.ts", source), write("../test/pipe.limit.test.ts", limitTest)];
const formatted = spawnSync("biome", ["format", "--write", ...paths], { encoding: "utf8" });
if (formatted.status !== 0) {
  console.error(formatted.stderr);
  process.exit(1);
}
console.log(`gen-pipe: src/pipe.ts and test/pipe.limit.test.ts, pipe and flow up to ${max} steps`);
